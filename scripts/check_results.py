#!/usr/bin/env python3
"""Verify (or regenerate) the generated tables in RESULTS.md.

    uv run python scripts/check_results.py          # rerun every block's command and diff; exit 1 on any mismatch
    uv run python scripts/check_results.py --write  # replace each block with fresh output

A generated block shows its command in a collapsible "Generated by" section
(GitHub renders <details>), followed by the output and an end marker:

    <details><summary>Generated by</summary>

    ```
    uv run python -m noncanon.compare --table ... \\
        "label=out/run/dapo_sample500" ...
    ```

    </details>

    | table ... |
    <!-- end generated -->

The command runs from the repository root with the metrics of every cell
under out/ (download them from the HF dataset or rerun
scripts/recompute_metrics.sh first). Its stdout, stripped, must equal the
block's content, stripped.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path

OPEN = "<details><summary>Generated by</summary>"
END = "<!-- end generated -->"
BLOCK = re.compile(re.escape(OPEN) + r"\n\n```\n(?P<cmd>.*?)\n```\n\n</details>\n\n(?P<body>.*?)" + re.escape(END), re.S)


def command(raw: str) -> str:
    """Join continuation lines (trailing backslash) into one shell command."""
    return " ".join(line.strip().removesuffix("\\").strip() for line in raw.splitlines())


def check_structure(text: str) -> None:
    opens = [m.start() for m in re.finditer(re.escape(OPEN), text)]
    ends = [m.start() for m in re.finditer(re.escape(END), text)]
    if len(opens) != len(ends):
        sys.exit(f"{len(opens)} 'Generated by' openers but {len(ends)} end markers")
    for o, e in zip(opens, ends):
        if not o < e:
            sys.exit("a generated block's end marker precedes its opener")
    for o, next_o, e in zip(opens, opens[1:], ends):
        if not e < next_o:
            sys.exit("a generated block is missing its end marker (the next block's opener comes first)")
    if len(BLOCK.findall(text)) != len(opens):
        sys.exit("a 'Generated by' block does not have the expected shape (fenced command, blank line, </details>, blank line)")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", type=Path, default=Path(__file__).resolve().parent.parent / "RESULTS.md")
    ap.add_argument("--write", action="store_true", help="replace block contents with fresh output instead of checking")
    args = ap.parse_args()
    root = Path(__file__).resolve().parent.parent
    text = args.file.read_text()
    check_structure(text)
    blocks = list(BLOCK.finditer(text))
    if not blocks:
        sys.exit(f"no generated blocks in {args.file}")
    failed, mismatched, out, last = 0, 0, [], 0
    for m in blocks:
        cmd = command(m.group("cmd"))
        proc = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=root)
        recorded = m.group("body").strip()
        fresh = proc.stdout.strip()
        if proc.returncode or not fresh:
            failed += 1
            print(f"FAILED   {cmd[:100]}\n  exit {proc.returncode}, {len(fresh)} bytes of output\n{proc.stderr.strip()[-2000:]}")
            fresh = recorded  # never write an empty or failed result over a block
        elif fresh == recorded:
            print(f"ok       {cmd[:100]}")
        else:
            mismatched += 1
            print(f"MISMATCH {cmd[:100]}")
            print("\n".join(difflib.unified_diff(recorded.splitlines(), fresh.splitlines(), "RESULTS.md", "regenerated", lineterm="")))
        out.append(text[last:m.start("body")] + fresh + "\n")
        last = m.end("body")
    out.append(text[last:])
    if args.write:
        args.file.write_text("".join(out))
        print(f"wrote {args.file}: {mismatched} of {len(blocks)} blocks updated" + (f", {failed} left unchanged because their command failed" if failed else ""))
        if failed:
            sys.exit(1)
    elif mismatched or failed:
        sys.exit(f"{mismatched} of {len(blocks)} generated blocks differ from their command's output; {failed} commands failed")
    else:
        print(f"all {len(blocks)} generated blocks match")


if __name__ == "__main__":
    main()
